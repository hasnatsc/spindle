-- -----------------------------------------------------------------------------
-- 4. Bookings (depends on org_organizations, acc_journal_entry_master,
--              acc_chart_of_accounts_sub, sec_users, crm_leads, crm_opportunities)
-- -----------------------------------------------------------------------------

CREATE TABLE trv_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    created_by VARCHAR(100),
    updated_at TIMESTAMP(6),
    updated_by VARCHAR(100),
    approval_request_id BIGINT,
    booking_date DATE NOT NULL,
    booking_no VARCHAR(50) NOT NULL,
    booking_type VARCHAR(20) NOT NULL CHECK ((booking_type)::text = ANY (ARRAY['PACKAGE'::character varying, 'HOTEL'::character varying, 'AIR'::character varying, 'COMBINED'::character varying])),
    currency VARCHAR(3) NOT NULL,
    discount_amount NUMERIC(18,2) NOT NULL,
    due_amount NUMERIC(18,2) NOT NULL,
    exchange_rate NUMERIC(18,4) NOT NULL,
    journal_entry_id BIGINT,
    lead_id BIGINT,
    opportunity_id BIGINT,
    paid_amount NUMERIC(18,2) NOT NULL,
    party_id BIGINT,
    remarks VARCHAR(1000),
    sales_agent_id BIGINT,
    status VARCHAR(20) NOT NULL CHECK ((status)::text = ANY (ARRAY['DRAFT'::character varying, 'CONFIRMED'::character varying, 'PARTIALLY_PAID'::character varying, 'PAID'::character varying, 'CANCELLED'::character varying, 'COMPLETED'::character varying])),
    subtotal_amount NUMERIC(18,2) NOT NULL,
    tax_amount NUMERIC(18,2) NOT NULL,
    total_amount NUMERIC(18,2) NOT NULL,
    travel_end_date DATE,
    travel_start_date DATE,
    organization_id BIGINT NOT NULL REFERENCES org_organizations(id),
    CONSTRAINT uq_trv_booking_org_no UNIQUE (organization_id, booking_no)
);
ALTER TABLE trv_bookings OWNER TO postgres;

CREATE TABLE trv_booking_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cost_center_id BIGINT,
    created_at TIMESTAMP(6),
    created_by VARCHAR(100),
    description VARCHAR(500),
    discount_amount NUMERIC(18,2) NOT NULL,
    line_total NUMERIC(18,2) NOT NULL,
    quantity NUMERIC(12,3) NOT NULL,
    reference_id BIGINT,
    service_type VARCHAR(20) NOT NULL CHECK ((service_type)::text = ANY (ARRAY['HOTEL'::character varying, 'AIR'::character varying, 'PACKAGE'::character varying, 'TOUR'::character varying, 'VISA'::character varying])),
    tax_amount NUMERIC(18,2) NOT NULL,
    unit_cost NUMERIC(18,2) NOT NULL,
    unit_price NUMERIC(18,2) NOT NULL,
    updated_at TIMESTAMP(6),
    updated_by VARCHAR(100),
    booking_id BIGINT NOT NULL REFERENCES trv_bookings(id)
);
ALTER TABLE trv_booking_services OWNER TO postgres;

CREATE TABLE trv_passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    created_by VARCHAR(100),
    updated_at TIMESTAMP(6),
    updated_by VARCHAR(100),
    date_of_birth DATE,
    email VARCHAR(150),
    first_name VARCHAR(100) NOT NULL,
    gender VARCHAR(10) CHECK ((gender)::text = ANY (ARRAY['MALE'::character varying, 'FEMALE'::character varying, 'OTHER'::character varying])),
    is_lead_passenger BOOLEAN NOT NULL,
    last_name VARCHAR(100),
    nationality VARCHAR(100),
    passenger_type VARCHAR(10) NOT NULL CHECK ((passenger_type)::text = ANY (ARRAY['ADULT'::character varying, 'CHILD'::character varying, 'INFANT'::character varying])),
    passport_expiry DATE,
    passport_number VARCHAR(50),
    phone VARCHAR(30),
    remarks VARCHAR(500),
    title VARCHAR(10),
    organization_id BIGINT NOT NULL REFERENCES org_organizations(id),
    booking_id BIGINT NOT NULL REFERENCES trv_bookings(id)
);
ALTER TABLE trv_passengers OWNER TO postgres;

CREATE TABLE trv_passenger_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dietary_restriction VARCHAR(300),
    meal_preference VARCHAR(100),
    passenger_id BIGINT NOT NULL CONSTRAINT uq_trv_pass_pref UNIQUE REFERENCES trv_passengers(id),
    remarks VARCHAR(500),
    seat_preference VARCHAR(100),
    special_assistance VARCHAR(300)
);
ALTER TABLE trv_passenger_preferences OWNER TO postgres;

CREATE TABLE trv_booking_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES trv_bookings(id),
    created_at TIMESTAMP(6),
    created_by VARCHAR(100),
    note_text OID NOT NULL,
    note_type VARCHAR(20) NOT NULL CHECK ((note_type)::text = ANY (ARRAY['INTERNAL'::character varying, 'CUSTOMER'::character varying]))
);
ALTER TABLE trv_booking_notes OWNER TO postgres;

CREATE TABLE trv_booking_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    changed_at TIMESTAMP(6),
    changed_by VARCHAR(100),
    remarks VARCHAR(500),
    status VARCHAR(20) NOT NULL
);
ALTER TABLE trv_booking_status_history OWNER TO postgres;

