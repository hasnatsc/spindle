-- =============================================================================
-- Travel Module Schema (trv_*)
-- Version: V8
-- Description: Core travel schema including airlines, airports, hotels,
--              packages, tours, bookings, air tickets, visa applications,
--              and related entities.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Independent tables (no foreign key dependencies)
-- -----------------------------------------------------------------------------

CREATE TABLE trv_airlines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airline_code VARCHAR(3) NOT NULL CONSTRAINT uq_trv_airline_code UNIQUE,
    airline_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMP(6),
    is_active BOOLEAN NOT NULL
);
ALTER TABLE trv_airlines OWNER TO postgres;

CREATE TABLE trv_airports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airport_code VARCHAR(3) NOT NULL CONSTRAINT uq_trv_airport_code UNIQUE,
    airport_name VARCHAR(200) NOT NULL,
    city VARCHAR(100),
    country VARCHAR(100),
    created_at TIMESTAMP(6)
);
ALTER TABLE trv_airports OWNER TO postgres;

CREATE TABLE trv_cabin_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_code VARCHAR(10) NOT NULL CONSTRAINT uq_trv_cabin_class_code UNIQUE,
    class_name VARCHAR(100) NOT NULL
);
ALTER TABLE trv_cabin_classes OWNER TO postgres;

CREATE TABLE trv_meal_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    description VARCHAR(300),
    plan_code VARCHAR(10) NOT NULL CONSTRAINT uq_trv_meal_plan_code UNIQUE,
    plan_name VARCHAR(100) NOT NULL
);
ALTER TABLE trv_meal_plans OWNER TO postgres;

CREATE TABLE trv_tour_guides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150),
    guide_name VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL,
    languages VARCHAR(200),
    phone VARCHAR(30)
);
ALTER TABLE trv_tour_guides OWNER TO postgres;

CREATE TABLE trv_visa_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country VARCHAR(100) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    description VARCHAR(500),
    fee_amount NUMERIC(18,2) NOT NULL,
    processing_days INTEGER,
    visa_category VARCHAR(100) NOT NULL
);
ALTER TABLE trv_visa_types OWNER TO postgres;

